// Secure handling of application documents. Framework-free CommonJS so it can be unit-tested with Hardhat/Mocha.
//
// Security model
//   * Every request is signed by the applicant's wallet (EIP-191 personal_sign over a canonical message that names
//     the action, applicant, application, document, file hash and a timestamp). The server recovers the signer and
//     requires it to equal the applicant. That binds each file to the correct user without passwords, and a
//     signature for one file/action cannot be reused for another.
//   * Files are checked by size and by CONTENT (magic bytes), not by the name or the browser's claimed type.
//   * Stored names are generated by the server (never taken from the client), under a per-applicant directory,
//     with path-traversal impossible by construction (ids are validated against strict patterns).
//   * Files live outside the public web root and are served only through signed requests.
//   * The application hash (what the contract anchors) covers the answers and every document's SHA-256.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { message } = require("../shared/signing");
const { LIMITS, DOCUMENTS, SCHEMA_VERSION, documentsFor, missingDocuments, validateAnswers } = require("../shared/requirements");

const ADDRESS_RE = /^0x[0-9a-fA-F]{40}$/;
const APP_ID_RE = /^[a-zA-Z0-9-]{8,64}$/;
const SHA_RE = /^[0-9a-f]{64}$/;
const MAX_SKEW_SECONDS = 10 * 60;

class DocError extends Error {
  constructor(status, message) { super(message); this.status = status; }
}

function sniff(buf) {
  if (buf.length >= 5 && buf.subarray(0, 5).toString("latin1") === "%PDF-") return { ext: "pdf", mime: "application/pdf" };
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return { ext: "jpg", mime: "image/jpeg" };
  if (buf.length >= 8 && buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return { ext: "png", mime: "image/png" };
  return null;
}

const sha256Hex = (buf) => crypto.createHash("sha256").update(buf).digest("hex");
const safeName = (n) => String(n || "file").replace(/[^\w.\- ]+/g, "_").replace(/\.{2,}/g, ".").replace(/^[. ]+/, "").slice(0, 80) || "file";

function verifySigner(msg, signature, expected) {
  const { verifyMessage } = require("ethers"); // loaded lazily so the pure helpers above work without it
  let signer;
  try { signer = verifyMessage(msg, signature); } catch { throw new DocError(401, "Invalid signature."); }
  if (signer.toLowerCase() !== String(expected).toLowerCase()) throw new DocError(403, "Signature does not match the applicant.");
  return signer;
}

function checkIssued(issued, nowSeconds = Math.floor(Date.now() / 1000)) {
  const n = Number(issued);
  if (!Number.isInteger(n) || Math.abs(nowSeconds - n) > MAX_SKEW_SECONDS) throw new DocError(401, "Request expired. Check your device clock and try again.");
  return n;
}

function checkIds({ applicant, application, document }) {
  if (!ADDRESS_RE.test(applicant || "")) throw new DocError(400, "Invalid applicant.");
  if (!APP_ID_RE.test(application || "")) throw new DocError(400, "Invalid application id.");
  if (document !== undefined && !Object.prototype.hasOwnProperty.call(DOCUMENTS, document)) throw new DocError(400, "Unknown document type.");
}

// Validates an uploaded file; returns {ext, mime, sha256}.
function inspectUpload(buf, claimedSha) {
  if (!buf || buf.length === 0) throw new DocError(400, "The file is empty.");
  if (buf.length > LIMITS.maxBytes) throw new DocError(413, `The file is larger than ${LIMITS.maxBytes / 1024 / 1024} MB.`);
  const type = sniff(buf);
  if (!type) throw new DocError(415, "Unsupported file. Upload a PDF, JPG or PNG.");
  const sha = sha256Hex(buf);
  if (claimedSha !== undefined && sha !== claimedSha) throw new DocError(400, "The file does not match the signed hash.");
  return { ...type, sha256: sha };
}

class DocumentStore {
  constructor(root) { this.root = root; }

  dirFor(applicant, application, scope) {
    const owner = String(applicant).toLowerCase();
    return path.join(this.root, owner, scope === "applicant" ? "profile" : application);
  }
  metaPath(dir, document) { return path.join(dir, `${document}.json`); }

  put({ applicant, application, document, buffer, originalName }) {
    checkIds({ applicant, application, document });
    const def = DOCUMENTS[document];
    const info = inspectUpload(buffer);
    const dir = this.dirFor(applicant, application, def.scope);
    fs.mkdirSync(dir, { recursive: true });
    this._removeFiles(dir, document);
    const file = `${document}.${info.ext}`;
    fs.writeFileSync(path.join(dir, file), buffer, { mode: 0o600 });
    const meta = {
      document, scope: def.scope, applicant: String(applicant).toLowerCase(), application: def.scope === "applicant" ? null : application,
      file, originalName: safeName(originalName), mime: info.mime, size: buffer.length, sha256: info.sha256, uploadedAt: new Date().toISOString(),
    };
    fs.writeFileSync(this.metaPath(dir, document), JSON.stringify(meta, null, 2), { mode: 0o600 });
    return meta;
  }

  _removeFiles(dir, document) {
    if (!fs.existsSync(dir)) return false;
    let removed = false;
    for (const f of fs.readdirSync(dir)) {
      if (f === `${document}.json` || /^[a-z_]+\.(pdf|jpg|png)$/.test(f) && f.split(".")[0] === document) { fs.unlinkSync(path.join(dir, f)); removed = true; }
    }
    return removed;
  }

  remove({ applicant, application, document }) {
    checkIds({ applicant, application, document });
    return this._removeFiles(this.dirFor(applicant, application, DOCUMENTS[document].scope), document);
  }

  get({ applicant, application, document }) {
    checkIds({ applicant, application, document });
    const dir = this.dirFor(applicant, application, DOCUMENTS[document].scope);
    const mp = this.metaPath(dir, document);
    if (!fs.existsSync(mp)) return null;
    const meta = JSON.parse(fs.readFileSync(mp, "utf8"));
    return { meta, path: path.join(dir, meta.file) };
  }

  // Everything attached to an application: its own documents plus the applicant's profile documents.
  list({ applicant, application }) {
    checkIds({ applicant, application });
    const out = [];
    for (const [id, def] of Object.entries(DOCUMENTS)) {
      const hit = this.get({ applicant, application, document: id });
      if (hit) out.push({ ...hit.meta, id, label: def.label });
    }
    return out;
  }

  // Server-side completeness check + canonical hash of the whole application.
  finalize({ applicant, application, ctx, answers = {}, extra = {} }) {
    checkIds({ applicant, application });
    const docs = this.list({ applicant, application });
    const missing = missingDocuments(ctx, docs.map((d) => d.document));
    if (missing.length) throw new DocError(422, `Missing required documents: ${missing.join(", ")}.`);
    const errors = validateAnswers(ctx, answers);
    if (Object.keys(errors).length) throw new DocError(422, `Invalid answers: ${Object.values(errors).join(" ")}`);
    const applicable = new Set(documentsFor(ctx).map((d) => d.id));
    const record = {
      schemaVersion: SCHEMA_VERSION,
      application, applicant: String(applicant).toLowerCase(),
      ctx: { cover: Number(ctx.cover), productId: Number(ctx.productId), assetId: Number(ctx.assetId), sumInsured: String(ctx.sumInsured) },
      answers,
      documents: docs.filter((d) => applicable.has(d.document)).map((d) => ({ document: d.document, sha256: d.sha256, size: d.size, mime: d.mime }))
        .sort((a, b) => a.document.localeCompare(b.document)),
      extra,
    };
    const canonical = JSON.stringify(record);
    const hash = "0x" + sha256Hex(Buffer.from(canonical));
    const dir = this.dirFor(applicant, application, "application");
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "application.json"), JSON.stringify({ ...record, applicationHash: hash, finalizedAt: new Date().toISOString() }, null, 2), { mode: 0o600 });
    return { applicationHash: hash, record };
  }

  link({ applicant, application, policyId }) {
    checkIds({ applicant, application });
    const f = path.join(this.dirFor(applicant, application, "application"), "application.json");
    if (!fs.existsSync(f)) throw new DocError(404, "Application not finalized.");
    const rec = JSON.parse(fs.readFileSync(f, "utf8"));
    if (rec.policyId) throw new DocError(409, "Application already linked to a policy.");
    rec.policyId = Number(policyId);
    rec.linkedAt = new Date().toISOString();
    fs.writeFileSync(f, JSON.stringify(rec, null, 2), { mode: 0o600 });
    return rec;
  }
}

function defaultRoot() { return process.env.UPLOAD_DIR || path.join(process.cwd(), ".data", "uploads"); }

module.exports = { DocError, DocumentStore, sniff, sha256Hex, safeName, message, verifySigner, checkIssued, checkIds, inspectUpload, defaultRoot, MAX_SKEW_SECONDS };
