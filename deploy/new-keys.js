// Prints a fresh set of keys for a public-network deployment, as .env lines: one key per role (no key holds two
// roles), plus the service secrets. Nothing is written to disk.
//   node deploy/new-keys.js >> .env        then fund the addresses printed on stderr from a faucet
// Keep .env private and backed up: these keys control the deployment, and PHONE_KEY_SECRET decrypts farmers' keys.
const crypto = require("crypto");
const { Wallet } = require("ethers");

// [private-key variable, address variable read by scripts/deploy.js, who it is]
const ROLES = [
  ["PRIVATE_KEY", null, "deployer (pays for the deployment, ~1 POL)"],
  ["UNDERWRITER_PRIVATE_KEY", "UNDERWRITER_ADDRESS", "underwriter (insurer)"],
  ["ORACLE_PRIVATE_KEY", "ORACLE_ADDRESS", "oracle service (posts weather/NDVI readings)"],
  ["AGENT_PRIVATE_KEY", "USSD_AGENT_ADDRESS", "USSD gateway (files claims for phone farmers)"],
  ["VET_PRIVATE_KEY", "VET_ADDRESS", "certified vet"],
  ["GOVERNMENT_PRIVATE_KEY", "GOVERNMENT_ADDRESS", "premium-subsidy programme"],
  ["VET_REGISTRAR_PRIVATE_KEY", "VET_REGISTRAR_ADDRESS", "vet registrar"],
  ["GUARDIAN_PRIVATE_KEY", "GUARDIAN_ADDRESS", "guardian (emergency pause)"],
  ["TREASURY_PRIVATE_KEY", "TREASURY_ADDRESS", "treasury (mints MockRWF, credits MoMo premiums)"],
  ["BUNDLER_PRIVATE_KEY", null, "bundler relayer (pays gas for farmers' smart accounts)"],
];

const lines = ["", `# --- generated by deploy/new-keys.js on ${new Date().toISOString()} ---`];
for (const [keyVar, addrVar, who] of ROLES) {
  const w = Wallet.createRandom();
  lines.push(`# ${who}: ${w.address}`, `${keyVar}=${w.privateKey}`);
  if (addrVar) lines.push(`${addrVar}=${w.address}`);
  console.error(`${w.address}  ${who}`);
}
lines.push("# shared secrets for the phone services",
  `CALLBACK_TOKEN=${crypto.randomBytes(24).toString("hex")}`,
  `PHONE_KEY_SECRET=${crypto.randomBytes(32).toString("hex")}`, "");
console.log(lines.join("\n"));
